-- SPC software export: subgroups, typed. One row per export row.

select
    nullif(trim(subgroup_id), '') as subgroup_id,
    nullif(trim(run_id), '') as run_id,
    nullif(trim(characteristic_id), '') as characteristic_id,
    cast(nullif(trim(subgroup_no), '') as bigint) as subgroup_no,
    cast(nullif(trim(sample_time), '') as timestamp) as sample_time,
    cast(nullif(trim(recorded_at), '') as timestamp) as recorded_at,
    nullif(trim(operator_id), '') as operator_id,
    nullif(trim(gauge_id), '') as gauge_id,
    nullif(trim(entry_method), '') as entry_method,
    nullif(trim(subgroup_type), '') as subgroup_type,
    cast(nullif(trim(pieces), '') as bigint) as pieces,
    nullif(trim(coil_id), '') as coil_id,
    cast(nullif(trim(r1), '') as double) as r1,
    cast(nullif(trim(r2), '') as double) as r2,
    cast(nullif(trim(r3), '') as double) as r3,
    cast(nullif(trim(r4), '') as double) as r4,
    cast(nullif(trim(r5), '') as double) as r5,
    cast(nullif(trim(r6), '') as double) as r6,
    cast(nullif(trim(r7), '') as double) as r7,
    cast(nullif(trim(r8), '') as double) as r8,
    cast(nullif(trim(r9), '') as double) as r9,
    cast(nullif(trim(r10), '') as double) as r10,
    cast(nullif(trim(attribute_count), '') as bigint) as attribute_count,
    cast(nullif(trim("mean"), '') as double) as "mean",
    cast(nullif(trim("range"), '') as double) as "range",
    nullif(trim(limit_set_id), '') as limit_set_id,
    nullif(trim(limit_status), '') as limit_status,
    cast(nullif(trim(centre_line), '') as double) as centre_line,
    cast(nullif(trim(ucl_mean), '') as double) as ucl_mean,
    cast(nullif(trim(lcl_mean), '') as double) as lcl_mean,
    cast(nullif(trim(ucl_range), '') as double) as ucl_range,
    cast(nullif(trim(lcl_range), '') as double) as lcl_range,
    cast(nullif(trim(ucl_moving_range), '') as double) as ucl_moving_range,
    cast(nullif(trim(coil_change_centre), '') as double) as coil_change_centre,
    cast(nullif(trim(coil_change_ucl), '') as double) as coil_change_ucl,
    cast(nullif(trim(coil_change_lcl), '') as double) as coil_change_lcl,
    nullif(trim(alarm_flags), '') as alarm_flags,
    (nullif(trim(adjustment_flag), '') = 'Y') as adjustment_flag,
    nullif(trim(export_batch_id), '') as export_batch_id
from {{ source('raw', 'spc__subgroups') }}
